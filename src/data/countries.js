const NAME_CONTINENT_FALLBACK = {
  somaliland: "AF",
  ncyprus: "EU",
  siachenglacier: "AS"
};

export function getContinentForCountry(iso, rawName) {
  const code = (iso && ISO_TO_CONTINENT[iso.toLowerCase()]) ||
    NAME_CONTINENT_FALLBACK[normalizeName(rawName)] ||
    "EU";
  return CONTINENTS[code] || CONTINENTS.EU;
}

export const COUNTRY_INFO = new Map(
  Object.entries(RAW_COUNTRIES).map(([name, [iso, langs]]) => {
    const continent = getContinentForCountry(iso, name);
    return [
      normalizeName(name),
      {
        iso,
        continent: continent.code,
        continentName: continent.name,
        continentHue: continent.hue,
        langs: langs ? langs.split(",") : []
      },
    ];
  })
);

export function lookupCountry(name) {
  const norm = normalizeName(name);
  if (COUNTRY_INFO.has(norm)) {
    return COUNTRY_INFO.get(norm);
  }
  const continent = getContinentForCountry("", name);
  return {
    iso: "",
    continent: continent.code,
    continentName: continent.name,
    continentHue: continent.hue,
    langs: ["en"],
    unknown: true
  };
}
